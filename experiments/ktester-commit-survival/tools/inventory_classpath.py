def props(text):
 return dict(line.split('=',1) for line in text.splitlines() if '=' in line and not line.startswith('#'))
def manifest(text):
 text=text.replace('\r\n','\n').replace('\n ','');return dict(line.split(': ',1) for line in text.splitlines() if ': ' in line)
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--kt',type=pathlib.Path,required=True);args=ap.parse_args();entries=[]
 folders=['data/projects/commons-codec/libs','code/dependencies']
 for folder in folders:
  for jar in sorted((args.kt/folder).glob('*.jar')):
   with zipfile.ZipFile(jar) as z:
    coordinates=[]
    for name in z.namelist():
     if name.startswith('META-INF/maven/') and name.endswith('/pom.properties'):
      p=props(z.read(name).decode());coordinates.append({'path':name,'coordinate':':'.join(p[k] for k in ['groupId','artifactId','version'])})
    mf=manifest(z.read('META-INF/MANIFEST.MF').decode()) if 'META-INF/MANIFEST.MF' in z.namelist() else {}
   if len(coordinates)==1:coordinate=coordinates[0]['coordinate'];evidence='pom.properties'
   elif jar.name in PRIMARY:
    coordinate=next(p['coordinate'] for p in coordinates if p['coordinate'].startswith(PRIMARY[jar.name]+':'));evidence='primary embedded pom.properties; shaded dependency coordinates recorded separately'
   else:coordinate=FALLBACK[jar.name];evidence='NO pom.properties: coordinate inferred from jar filename and manifest; verify against Central bytes'
   entries.append({'source':folder+'/'+jar.name,'filename':jar.name,'bytes':jar.stat().st_size,'sha256':hashlib.sha256(jar.read_bytes()).hexdigest(),'coordinate':coordinate,'classifier':'nodeps' if jar.name=='jacococli.jar' else '', 'coordinate_evidence':evidence,'embedded_maven_properties':coordinates,'manifest':mf})
 # Fetch the runnable classpath first, then audit auxiliary tool dependencies.
 entries.sort(key=lambda x:('code/dependencies' in x['source'] and not x['filename'].startswith('junit-platform-console'),x['filename']))
 (EXPERIMENT/'tools/jar-inventory.json').write_text(json.dumps(entries,indent=2)+'\n')
 lines=['# Exact supplied artifacts. One groupId:artifactId:version coordinate per line.', '# Generated by inventory_classpath.py; full embedded metadata, sizes and SHA-256 are in jar-inventory.json.', '# No version substitution is authorized. Snapshot coordinates may be unavailable from Maven Central.', '# jacococli.jar is a shaded CLI: fetch classifier=nodeps; jacocoagent.jar exposes internal artifact org.jacoco.agent.rt.']
